function score(query: string, topic: HelpTopic): number {
  const q = new Set(tokenize(query));
  if (q.size === 0) return 0;
  const t = new Set(tokenize(`${topic.title} ${topic.title} ${topic.body}`));
  let hit = 0;
  for (const tok of q) if (t.has(tok)) hit++;
  return hit / q.size;
}

/** 質問に関係するヘルプの項目（関係の深い順） */
export function searchHelp(query: string, limit = 3): HelpTopic[] {
  return HELP_TOPICS.map((t) => ({ t, s: score(query, t) }))
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s)
    .slice(0, limit)
    .map((x) => x.t);
}

/** 使い方モードで、質問の前に付けるヘルプの抜粋 */
export function helpContext(query: string): string {
  const topics = searchHelp(query);
  const body = topics.length
    ? topics.map((t) => `## ${t.title}\n${t.body}`).join('\n\n')
    : '（関係するヘルプは見つかりませんでした）';
  return `<help>\n${body}\n</help>\n上のヘルプだけをもとに、アプリの使い方に答えてください。ヘルプに書かれていないことは「ヘルプには見当たりません」と答えてください。`;
}
